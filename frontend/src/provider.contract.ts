import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { it, expect } from 'vitest';
import { answerSchema, capabilitiesSchema, documentSchema, pageSchema, passageSchema, searchSchema } from './api';
import { reportSchema } from './EvaluationReport';

it('validates actual serialized API lifecycle and search responses against the consumer', () => {
  const python = process.env.ATLAS_PYTHON ?? resolve('..', '.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
  const raw = execFileSync(python, ['scripts/provider_contract.py'], { encoding: 'utf8', timeout: 20000 });
  const data: Record<string, unknown> = JSON.parse(raw);
  const document = documentSchema.parse(data.document);
  const documents = pageSchema(documentSchema).parse(data.documents);
  const chunks = pageSchema(passageSchema).parse(data.chunks);
  const citation = passageSchema.parse(data.citation);
  const found = searchSchema.parse(data.search);
  const empty = searchSchema.parse(data.empty_search);
  expect(documents.items[0]?.id).toBe(document.id);
  expect(chunks.items[0]?.id).toBe(citation.id);
  expect(citation.text).toContain('😀');
  expect(found.passages[0]?.id).toBe(citation.id);
  expect(empty.status).toBe('insufficient_evidence');
  expect(capabilitiesSchema.parse(data.capabilities).generation_enabled).toBe(true);
  expect(answerSchema.parse(data.answer).answer.claims[0]?.citation_ids).toContain(citation.id);
  expect(answerSchema.parse(data.abstention).answer.status).toBe('insufficient_evidence');
  const report = reportSchema.parse(data.evaluation);
  expect(report.official).toBe(false);
  expect(report.summary.retrieval_recall_at_k).toEqual({ value: 1, count: 1 });
  expect(report.summary.answer_correctness).toEqual({ value: null, count: 0 });
  expect(report.cases[0]?.estimated_cost_usd).toBeNull();
  const answers = reportSchema.parse(data.evaluation_answers);
  expect(answers.config.generate_answers).toBe(true);
  expect(answers.summary.citation_precision).toEqual({ value: 1, count: 1 });
  expect(answers.summary.abstention.count).toBe(1);
  expect(answers.summary.answer_correctness).toEqual({ value: null, count: 0 });
  expect(documentSchema.parse(data.html_document).media_type).toBe('text/html');
  const html = passageSchema.parse(data.html_passage);
  expect(html.heading).toBe('Rotation');
  expect(html.page_number).toBeNull();
  expect(html.text).not.toContain('untrusted');
});
